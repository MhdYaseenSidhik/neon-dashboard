import json, collections, sys
D='public/data/'
def L(n): return json.load(open(D+n))
out=['# Data profile — public/data (read-only input)\n','Generated by `scripts/profile_data.py`. Numbers below are counted from the files.\n']
m=L('manifest.json')
out.append(f"- asOf {m['asOf']}, plant {m['plantId']} ({m['plantName']}), backcastIncluded {m['backcastIncluded']}\n- Disclaimer: {m['disclaimer']}\n")
def prof(name, rows, keys):
    out.append(f"\n## {name}\nRows: {len(rows)}\n\n| field | non-null | distinct (<=12 shown) / min..max |\n|---|---|---|")
    for k in keys:
        vals=[r.get(k) for r in rows]; nn=[v for v in vals if v is not None]
        if nn and all(isinstance(v,(int,float)) and not isinstance(v,bool) for v in nn):
            d=f"{min(nn):g} .. {max(nn):g}"
        else:
            s=sorted(set(map(str,nn)))
            d=f"{len(s)} distinct: "+", ".join(s[:12]) if len(s)<=12 else f"{len(s)} distinct"
        out.append(f"| {k} | {len(nn)}/{len(vals)} | {d} |")
dims=L('dims.json')
out.append("\n## dims.json\n"+", ".join(f"{k}: {len(v)}" for k,v in dims.items()))
out.append("\nmaterialGroups: "+json.dumps(dims['materialGroups'])[:900])
out.append("\ncriticality: "+json.dumps(dims['criticality']))
k=L('kpis.json'); prof('kpis.json rows',k['rows'],['month','plantId','kpiCode','value','uom','scenario'])
out.append("\nCatalog:\n\n| code | label | uom | direction |\n|---|---|---|---|")
for c in k['catalog']: out.append(f"| {c['code']} | {c['label']} | {c['uom']} | {c['direction']} |")
cnt=collections.Counter(r['kpiCode'] for r in k['rows']); out.append("\nRows per code: "+", ".join(f"{a}={b}" for a,b in sorted(cnt.items())))
out.append("Plants in kpis: "+str(set(r['plantId'] for r in k['rows'])))
s=L('inventory_summary.json'); prof('inventory_summary.json',s['rows'],list(s['rows'][0]))
mt=L('materials.json'); prof('materials.json',mt['rows'],list(mt['rows'][0]))
r=L('reorder.json'); prof('reorder.json',r['rows'],list(r['rows'][0]))
p=L('plan_vs_actual.json'); prof('plan_vs_actual.json',p['rows'],list(p['rows'][0]))
h=L('forecast_holdout.json'); out.append(f"\n## forecast_holdout.json\nkind={h['kind']} metric={h['metric']} error={h['error']} leaderboard={len(h['leaderboard'])}")
prof('holdout.byPlantMonth',h['byPlantMonth'],list(h['byPlantMonth'][0])); prof('holdout.byUomMonth',h['byUomMonth'],list(h['byUomMonth'][0])); prof('holdout.series',h['series'],list(h['series'][0]))
f=L('forecast.json'); out.append(f"\n## forecast.json\navailable={f['available']} reason={f['reason']} kind={f['kind']} from {f['forecastFrom']} to {f['forecastTo']} horizons={f['horizons']}")
prof('forecast.byPlantMonth',f['byPlantMonth'],list(f['byPlantMonth'][0])); prof('forecast.byUomMonth',f['byUomMonth'],list(f['byUomMonth'][0])); prof('forecast.rows',f['rows'],list(f['rows'][0]))
# uom integrity
bad=sum(1 for x in mt['rows'] if not x.get('uom')); out.append(f"\n## Checks\n- materials without uom: {bad}")
out.append(f"- materials plants: {set(x['plantId'] for x in mt['rows'])}")
g=collections.defaultdict(float)
for x in mt['rows']: g[x['uom']]+=x['availableQty'] or 0
out.append("- availableQty per uom (materials.json): "+json.dumps({a:round(b,2) for a,b in g.items()}))
out.append("- top-level keys: "+json.dumps({n:list(L(n).keys()) for n in ['kpis.json','forecast.json','forecast_holdout.json']}))
open('docs/DATA_PROFILE.md','w').write("\n".join(out)+"\n"); print("ok")
